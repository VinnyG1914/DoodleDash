"""Rebuild js/avatars.js from the image files in the avatars/ folder.

Every sub-folder of avatars/ becomes a tab in the avatar picker (avatars/custom/ is shown first).
Photos bigger than 256 px are centre-cropped to a square and shrunk to 256 px so players load them fast.
The untouched originals are kept in avatars/_originals/.

Run it with "Update avatars.bat", then upload the TeamQuiz folder to Netlify again.
"""
import json, pathlib, re, shutil, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
AV = ROOT / "avatars"
OUT = ROOT / "js" / "avatars.js"
EXTS = {".svg", ".png", ".jpg", ".jpeg", ".webp", ".gif"}
ORDER = ["custom", "heroes", "cartoon", "smiles", "toons", "robots", "people"]
SIZE = 256


def shrink(path, group):
    try:
        from PIL import Image, ImageOps
    except ImportError:
        print("  (Pillow not installed, so", path.name, "is used as-is)")
        return path
    with Image.open(path) as im:
        if getattr(im, "is_animated", False):
            return path
        w, h = im.size
        if w <= SIZE and h <= SIZE and abs(w - h) <= 2:
            return path
        backup = AV / "_originals" / group / path.name
        backup.parent.mkdir(parents=True, exist_ok=True)
        if not backup.exists():
            shutil.copy2(path, backup)
        im = ImageOps.exif_transpose(im)
        side = min(im.size)
        left, top = (im.width - side) // 2, max(0, (im.height - side) // 3)  # keep faces: crop nearer the top
        im = im.crop((left, top, left + side, top + side)).resize((SIZE, SIZE), Image.LANCZOS)
        has_alpha = im.mode in ("RGBA", "LA", "P")
        out = path.with_suffix(".png" if has_alpha else ".jpg")
        if has_alpha:
            im.convert("RGBA").save(out, optimize=True)
        else:
            im.convert("RGB").save(out, quality=88, optimize=True)
        if out != path:
            path.unlink()
        print("  resized", path.name, "->", out.name)
        return out


def label(name):
    return re.sub(r"[-_]+", " ", name).strip().title()


def main():
    groups = []
    folders = sorted([d for d in AV.iterdir() if d.is_dir() and not d.name.startswith("_")],
                     key=lambda d: (ORDER.index(d.name) if d.name in ORDER else 99, d.name))
    for d in folders:
        items = []
        for f in sorted(d.iterdir(), key=lambda x: x.name.lower()):
            if f.suffix.lower() not in EXTS:
                continue
            if f.suffix.lower() != ".svg":
                f = shrink(f, d.name)
            items.append({"id": f"{d.name}/{f.stem}", "src": f"avatars/{d.name}/{f.name}"})
        if items:
            groups.append({"name": label(d.name), "items": items})
            print(f"{label(d.name)}: {len(items)} avatars")
    if not groups:
        sys.exit("No avatar images found in " + str(AV))
    OUT.write_text("/* Generated by tools/build_avatars.py - do not edit by hand. */\n"
                   "window.TQ_AVATAR_GROUPS = " + json.dumps(groups, indent=1) + ";\n", encoding="utf-8")
    print("Wrote", OUT.relative_to(ROOT), "with", sum(len(g["items"]) for g in groups), "avatars")


if __name__ == "__main__":
    main()
